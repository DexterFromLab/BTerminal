"""Mock Copilot CLI smoke — T2.4.

Verifies that:
  - tools/mock_ai_cli installed as `copilot` binary tolerates the argv
    generated by CopilotProvider.build_argv (TUI-safe flags + intro).
  - The bundled `tests/scenarios/copilot_basic.json` matches the
    canonical mock_ai_cli scenario schema and produces the expected
    replies on stdin → stdout.
  - find_binary() resolves a binary placed on $PATH (via shutil.which),
    not just the explicit search_paths list.

These tests don't spawn under VTE — they pipe stdin/stdout directly so
the assertion focuses on argv compatibility + scenario parsing rather
than TUI rendering. T2.10 covers the full VTE-on-mock E2E.
"""
from __future__ import annotations

import json
import os
import shutil
import stat
import subprocess
from pathlib import Path

import pytest

from bterminal.providers import load_providers_config
from bterminal.providers.copilot import CopilotProvider

REPO_ROOT = Path(__file__).parent.parent
MOCK_SRC = REPO_ROOT / "tools" / "mock_ai_cli"
SCENARIO_PATH = REPO_ROOT / "tests" / "scenarios" / "copilot_basic.json"


@pytest.fixture
def fake_copilot_binary(tmp_path):
    """Copy tools/mock_ai_cli into tmp_path/copilot and mark executable."""
    fake = tmp_path / "copilot"
    shutil.copy(str(MOCK_SRC), str(fake))
    fake.chmod(fake.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    return fake


@pytest.fixture
def copilot_provider(fake_copilot_binary):
    """CopilotProvider whose find_binary() resolves to the fake."""
    cfg = json.loads(json.dumps(load_providers_config()["providers"]["copilot"]))
    cfg["binary"]["search_paths"] = [str(fake_copilot_binary)]
    return CopilotProvider(cfg)


