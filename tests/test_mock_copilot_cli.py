# ─── PATH-based binary discovery ─────────────────────────────────────────────

def test_find_binary_via_path_search(tmp_path, monkeypatch, fake_copilot_binary):
    """When explicit search_paths come up empty, find_binary() falls
    back to shutil.which on $PATH. Place the fake binary in tmp_path
    and add tmp_path to PATH — find_binary must resolve it."""
    cfg = json.loads(json.dumps(load_providers_config()["providers"]["copilot"]))
    cfg["binary"]["search_paths"] = []  # force PATH fallback

    monkeypatch.setenv(
        "PATH",
        f"{tmp_path}{os.pathsep}{os.environ.get('PATH', '')}",
    )
    p = CopilotProvider(cfg)
    found = p.find_binary()
    assert found == str(fake_copilot_binary)


def test_find_binary_returns_none_when_path_clean(tmp_path, monkeypatch):
    """If neither search_paths nor PATH contains a copilot binary,
    find_binary() returns None — signal to spawn_ai_cli to render the
    'binary not found' error script."""
    cfg = json.loads(json.dumps(load_providers_config()["providers"]["copilot"]))
    cfg["binary"]["search_paths"] = [str(tmp_path / "nope")]
    # Strip PATH entirely (also block shutil.which fallback)
    monkeypatch.setenv("PATH", "")
    monkeypatch.setattr("bterminal.providers.copilot.shutil.which",
                        lambda *a, **kw: None)
    p = CopilotProvider(cfg)
    assert p.find_binary() is None
