# ─── Mock binary tolerates Copilot argv ──────────────────────────────────────

def test_mock_runs_with_copilot_argv(copilot_provider, fake_copilot_binary):
    """Subprocess spawn with the EXACT argv CopilotProvider.build_argv
    generates — mock must not crash on unknown flags. We pipe stdin
    `/exit` so the process terminates cleanly within the timeout."""
    argv = copilot_provider.build_argv({}, "")
    # First entry is the binary path (resolved by find_binary)
    assert argv[0] == str(fake_copilot_binary)
    # TUI-safe flags must be present (--no-banner removed 2026-05-07
    # — real copilot v1.0.43 uses opt-in `--banner`, not `--no-banner`)
    assert "--no-mouse" in argv
    assert "--plain-diff" in argv
    assert "--no-color" in argv

    env = {**os.environ, "MOCK_AI_CLI_SCENARIO": str(SCENARIO_PATH)}
    proc = subprocess.Popen(
        argv,
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        env=env,
        text=True,
    )
    stdout, _stderr = proc.communicate(input="/exit\n", timeout=10)
    assert proc.returncode == 0


